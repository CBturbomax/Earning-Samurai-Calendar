# 종성 붙이기용 — 한글 음절 = 0xAC00 + (초성*21 + 중성)*28 + 종성
JONG_N, JONG_S, JONG_M, JONG_K = 4, 19, 16, 1


def _add_final(syl: str, jong: int) -> str:
    """이미 만들어진 한글 음절에 받침을 얹는다. 받침이 있으면 그대로 둔다."""
    if not syl or not ("가" <= syl[-1] <= "힣"):
        return syl
    code = ord(syl[-1]) - 0xAC00
    if code % 28:                      # 이미 받침이 있으면 건드리지 않는다
        return syl
    return syl[:-1] + chr(0xAC00 + code + jong)


# 반복 기호(ゝゞヽヾ)는 앞 가나를 되풀이한다. ゞ·ヾ는 탁음까지 붙인다.
# いすゞ(이스즈)처럼 사명에 그대로 남아 있는 경우가 있다.
VOICED = dict(zip("カキクケコサシスセソタチツテトハヒフヘホ",
                  "ガギグゲゴザジズゼゾダヂヅデドバビブベボ"))


def _expand_repeats(s: str) -> str:
    out = []
    for ch in s:
        if ch in "ゝヽ" and out:
            out.append(out[-1])
        elif ch in "ゞヾ" and out:
            out.append(VOICED.get(out[-1], out[-1]))
        else:
            out.append(ch)
    return "".join(out)


def kana_to_hangul(s: str) -> str:
    """가타카나·히라가나 덩어리를 한글로. ー(장음)은 한글에서 표기하지 않는다."""
    # 히라가나를 가타카나로 올려 한 표로 처리한다
    s = "".join(chr(ord(c) + 0x60) if "ぁ" <= c <= "ゖ" else c for c in s)
    s = _expand_repeats(s)
    out = []
    i = 0
    while i < len(s):
        c = s[i]
        if c == "ー":                                   # 장음 무시
            i += 1; continue
        if c == "ッ":                                   # 촉음 -> ㅅ 받침
            # 어말 ック·ット 는 한국어 외래어 표기에서 받침으로 붙는다.
            # オービック -> 오빗쿠(x) 오빅(o), ロボット -> 로봇
            tail = s[i:i + 2]
            if out and i + 2 == len(s) and tail in ("ック", "ット"):
                out[-1] = _add_final(out[-1], JONG_K if tail == "ック" else JONG_S)
                i += 2; continue
            if out:
                out[-1] = _add_final(out[-1], JONG_S)
            i += 1; continue
        if c == "ン":                                   # 발음 -> ㄴ/ㅁ 받침
            nxt = s[i + 1] if i + 1 < len(s) else ""
            if out:
                out[-1] = _add_final(out[-1], JONG_M if nxt in M_ROW else JONG_N)
            i += 1; continue
        two = s[i:i + 2]
        if two in KANA2:
            out.append(KANA2[two]); i += 2; continue
        if c in KANA1:
            out.append(KANA1[c]); i += 1; continue
        if c in "・=＝":                                 # 중점은 공백으로
            out.append(" "); i += 1; continue
        out.append(c); i += 1
    return "".join(out)


